package br.com.paroquiasantacabrini.app.feature.pix.ui.model

import com.google.zxing.BarcodeFormat
import com.google.zxing.EncodeHintType
import com.google.zxing.qrcode.QRCodeWriter
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel

internal object QrCodeEncoder {

    internal fun encode(content: String): QrCodeMatrix {
        val hints = mapOf(
            EncodeHintType.ERROR_CORRECTION to ErrorCorrectionLevel.M,
            EncodeHintType.MARGIN to 0,
        )
        // A requested size of 0 keeps the matrix at its natural module count.
        val bits = QRCodeWriter().encode(content, BarcodeFormat.QR_CODE, 0, 0, hints)
        val size = bits.width
        val modules = BooleanArray(size * size) { index -> bits.get(index % size, index / size) }
        return QrCodeMatrix(size = size, modules = modules)
    }
}
